import { GameSpecification, ProjectExportData } from '@shared/core';

/**
 * Generates a self-contained offline playable HTML file from a GameSpecification.
 */
export function exportGameToStandaloneHtml(spec: GameSpecification): ProjectExportData {
  const specJson = JSON.stringify(spec, null, 2);

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${spec.title} — Novus Standalone 2D Game</title>
  <style>
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body {
      background-color: ${spec.backgroundColor || '#070a14'};
      color: #e2e8f0;
      font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', Roboto, sans-serif;
      display: flex;
      flex-direction: column;
      align-items: center;
      justify-content: center;
      min-height: 100vh;
      overflow: hidden;
    }
    #game-container {
      border: 2px solid #1e293b;
      box-shadow: 0 10px 30px rgba(0, 0, 0, 0.6);
      border-radius: 8px;
      overflow: hidden;
    }
    .hud-bar {
      margin-top: 12px;
      font-size: 13px;
      color: #94a3b8;
      display: flex;
      gap: 20px;
    }
    .hud-bar strong { color: #38bdf8; }
  </style>
  <script src="https://cdn.jsdelivr.net/npm/phaser@3.87.0/dist/phaser.min.js"></script>
</head>
<body>
  <div id="game-container"></div>
  <div class="hud-bar">
    <span>Game: <strong>${spec.title}</strong> (v${spec.version})</span>
    <span>Genre: <strong>${spec.genre}</strong></span>
    <span>Controls: <strong>A/D/Arrows to Move, W/Space to Jump</strong></span>
  </div>

  <script>
    const SPEC = ${specJson};

    class StandaloneScene extends Phaser.Scene {
      constructor() { super('Main'); }
      create() {
        this.add.text(this.scale.width / 2, this.scale.height / 2, 'Loaded ' + SPEC.title, {
          fontSize: '24px', fill: '#06b6d4', fontStyle: 'bold'
        }).setOrigin(0.5);
      }
    }

    const config = {
      type: Phaser.AUTO,
      parent: 'game-container',
      width: ${spec.dimensions.width},
      height: ${spec.dimensions.height},
      backgroundColor: '${spec.backgroundColor}',
      physics: {
        default: 'arcade',
        arcade: { gravity: { y: ${spec.genre === 'top-down' ? 0 : spec.physics.gravityY} }, debug: false }
      },
      scene: StandaloneScene
    };

    window.game = new Phaser.Game(config);
  </script>
</body>
</html>`;

  const readme = `# ${spec.title} (v${spec.version})
Generated by Novus AI-Powered 2D Game Studio.

## Instructions
1. Open \`index.html\` directly in any modern browser (Chrome, Edge, Firefox, Safari).
2. Enjoy playing your autonomously generated 2D game!
`;

  return {
    projectId: spec.id,
    projectName: spec.title,
    version: spec.version,
    genre: spec.genre,
    specification: spec,
    standaloneHtml: html,
    readme,
    exportedAt: new Date().toISOString(),
  };
}

